/// Centralized user-facing strings for HoneyChain.
///
/// Supported languages: English (en), Tamil (ta), Hindi (hi).
/// All beekeeper-facing text is localizable; the selected language is
/// persisted locally so the app works fully offline.
library;

class AppLang {
  const AppLang(this.code, this.nativeName, this.englishName);
  final String code;
  final String nativeName;
  final String englishName;
}

class AppLanguages {
  static const AppLang english = AppLang('en', 'English', 'English');
  static const AppLang tamil = AppLang('ta', 'தமிழ்', 'Tamil');
  static const AppLang hindi = AppLang('hi', 'हिन्दी', 'Hindi');

  static const List<AppLang> all = [english, tamil, hindi];

  static AppLang fromCode(String? code) {
    for (final lang in all) {
      if (lang.code == code) return lang;
    }
    return english;
  }
}

